package org.structr.common.trace;

/**
 * Where a call flow enters Structr: a request, a message, a scheduled task. Normally the root of its
 * flow; reached from inside a running flow it is an ordinary step of that flow.
 */
public abstract class EntryFrame extends CallFrame {

	protected EntryFrame(final String name, final String sessionId) {
		super(name, sessionId, false);
	}
}
